const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const base=path.resolve(__dirname,'../bili-youtube-danmaku');
const context=vm.createContext({URL});vm.runInContext(fs.readFileSync(path.join(base,'youtube.js'),'utf8'),context);
const Y=context.DanmakuYouTube;
for(const url of ['https://m.youtube.com/watch?v=a','https://www.youtube.com/watch?v=a'])assert.equal(Y.isUrl(url),true);
for(const url of ['https://m.youtube.com.evil.test/watch','https://evil.test/?u=https://m.youtube.com/','http://m.youtube.com/','https://u:p@m.youtube.com/','https://m.youtube.com:8443/'])assert.equal(Y.isUrl(url),false);
let desktop,container,full;
const doc={querySelector:s=>s==='#movie_player'?desktop:s==='#player-container-id'?container:null,get fullscreenElement(){return full}};
const parent={},video={parentElement:parent,closest:()=>null};container={querySelector:()=>video};
assert.equal(Y.player(doc),parent,'mobile fallback follows the actual video parent');
const html5={};video.closest=()=>html5;assert.equal(Y.player(doc),html5);
full={contains:v=>v===video};assert.equal(Y.player(doc),full,'container fullscreen includes the overlay');
full=video;assert.equal(Y.player(doc),html5,'never append a layer inside the native video element');
full=null;desktop={querySelector:()=>video};assert.equal(Y.player(doc),desktop,'desktop container remains supported');
desktop=null;container=null;assert.equal(Y.player(doc),null);
const manifest=JSON.parse(fs.readFileSync(path.join(base,'manifest.json'),'utf8'));
assert.ok(manifest.host_permissions.includes('https://m.youtube.com/*'));
assert.ok(manifest.content_scripts.some(c=>c.matches.includes('https://m.youtube.com/*') && c.js.includes('youtube.js') && c.js.includes('overlay.js')));
console.log('PASS: mobile and desktop URL allowlist, mobile player fallback, container/native fullscreen handling and manifest coverage');
